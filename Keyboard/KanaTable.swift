/// フリックキーの文字の割り当て。並びは [中央, 左, 上, 右, 下]（空文字は割り当てなし）
enum KanaTable {
    static let kanaRows: [[[String]]] = [
        [["あ", "い", "う", "え", "お"], ["か", "き", "く", "け", "こ"], ["さ", "し", "す", "せ", "そ"]],
        [["た", "ち", "つ", "て", "と"], ["な", "に", "ぬ", "ね", "の"], ["は", "ひ", "ふ", "へ", "ほ"]],
        [["ま", "み", "む", "め", "も"], ["や", "「", "ゆ", "」", "よ"], ["ら", "り", "る", "れ", "ろ"]],
    ]
    static let wa = ["わ", "を", "ん", "ー", ""]
    static let punctuation = ["、", "。", "？", "！", ""]

    static let numberRows: [[[String]]] = [
        [["1", "☆", "♪", "→", ""], ["2", "¥", "$", "€", ""], ["3", "%", "°", "#", ""]],
        [["4", "○", "*", "・", ""], ["5", "+", "×", "÷", ""], ["6", "<", "=", ">", ""]],
        [["7", "「", "」", ":", ""], ["8", "〒", "々", "〆", ""], ["9", "^", "|", "\\", ""]],
    ]
    static let brackets = ["(", ")", "[", "]", ""]
    static let zero = ["0", "〜", "…", "@", ""]
    static let dots = [".", ",", "-", "/", "_"]

    /// 「゛゜小」キーで順に切り替える文字の組
    private static let variants: [[Character]] = [
        "あぁ", "いぃ", "うぅゔ", "えぇ", "おぉ",
        "かが", "きぎ", "くぐ", "けげ", "こご",
        "さざ", "しじ", "すず", "せぜ", "そぞ",
        "ただ", "ちぢ", "つっづ", "てで", "とど",
        "はばぱ", "ひびぴ", "ふぶぷ", "へべぺ", "ほぼぽ",
        "やゃ", "ゆゅ", "よょ", "わゎ",
    ].map(Array.init)

    static func nextVariant(of character: Character) -> Character? {
        for group in variants {
            if let index = group.firstIndex(of: character) {
                return group[(index + 1) % group.count]
            }
        }
        return nil
    }
}
